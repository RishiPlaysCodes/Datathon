"""Deepfake / media-manipulation detection endpoint.

This is a REAL byte-level forensic heuristic engine (not a mock and not a CNN).
It inspects the uploaded file's actual bytes for signals that a genuine camera
photo would not carry: AI-generator metadata (Stable Diffusion / Midjourney /
DALL-E / C2PA manifests), image-editor signatures (Photoshop / GIMP / FaceApp),
absent camera EXIF, generative-model canvas dimensions, and byte entropy.
Each signal is explainable and the verdict is derived only from the file's real
content, so identical files always produce identical, auditable results.

It is advisory: for courtroom use, a certified digital-forensics lab is required.
"""
