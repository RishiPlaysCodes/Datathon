def _printable_text(data: bytes, cap: int = 300_000) -> str:
    """Extract printable ASCII runs from the head+tail of the file, lowercased."""
    head = data[:cap]
    tail = data[-8192:] if len(data) > cap else b""
    blob = head + tail
    out = bytearray()
    for byte in blob:
        out.append(byte if 32 <= byte < 127 else 32)
    return out.decode("ascii", errors="ignore").lower()


def _shannon_entropy(data: bytes, cap: int = 131_072) -> float:
    """Byte entropy (0-8 bits). Natural photos compress to very high entropy."""
    chunk = data[:cap]
    if not chunk:
        return 0.0
    freq = [0] * 256
    for byte in chunk:
        freq[byte] += 1
    n = len(chunk)
    entropy = 0.0
    for count in freq:
        if count:
            p = count / n
            entropy -= p * math.log2(p)
    return round(entropy, 3)


def _detect_format_and_dimensions(data: bytes):
    """Return (format, width, height) parsed from the actual file header."""
    if data[:8] == b"\x89PNG\r\n\x1a\n" and len(data) >= 24:
        width, height = struct.unpack(">II", data[16:24])
        return "png", width, height
    if data[:2] == b"\xff\xd8":
        i, n = 2, len(data)
        sof_markers = {0xC0, 0xC1, 0xC2, 0xC3, 0xC5, 0xC6, 0xC7, 0xC9, 0xCA, 0xCB, 0xCD, 0xCE, 0xCF}
        while i < n - 1:
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if marker in sof_markers and i + 9 <= n:
                height, width = struct.unpack(">HH", data[i + 5:i + 9])
                return "jpeg", width, height
            if marker in (0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
                i += 2
                continue
            if i + 4 <= n:
                seg_len = struct.unpack(">H", data[i + 2:i + 4])[0]
                i += 2 + seg_len
            else:
                break
        return "jpeg", None, None
    if data[:6] in (b"GIF87a", b"GIF89a") and len(data) >= 10:
        width, height = struct.unpack("<HH", data[6:10])
        return "gif", width, height
    if data[:4] == b"RIFF" and data[8:12] == b"WEBP":
        return "webp", None, None
    if data[4:12] in (b"ftypqt  ", b"ftypmp42", b"ftypisom", b"ftypmp41") or data[4:8] == b"ftyp":
        return "mp4", None, None
    return "unknown", None, None


def _pixel_level_analysis(data: bytes, fmt: str) -> list:
    """Pixel-level statistical forensics: noise variance, JPEG ghost, color consistency.

    Works on raw decompressed pixel data extracted from the file bytes.
    Does NOT require PIL/OpenCV — operates directly on the byte stream.
    """
    signals = []

    if fmt == "png" and len(data) > 100:
        # PNG: check IDAT chunk compression ratio — AI-generated PNGs often have
        # unusually uniform pixel regions producing very high compression ratios.
        idat_sizes = []
        i = 8  # skip PNG signature
        total_idat = 0
        while i + 8 <= len(data):
            chunk_len = int.from_bytes(data[i:i + 4], "big")
            chunk_type = data[i + 4:i + 8]
            if chunk_type == b"IDAT":
                total_idat += chunk_len
                idat_sizes.append(chunk_len)
            i += 12 + chunk_len  # length + type + data + crc
            if chunk_type == b"IEND":
                break
        # A genuine photo's IDAT typically compresses to 60-95% of raw pixel size.
        # AI-generated images with large uniform areas compress much more.
        if total_idat > 0 and len(data) > 1000:
            compression_ratio = total_idat / len(data)
            if compression_ratio < 0.25:
                signals.append({
                    "name": "Abnormal PNG compression",
                    "detail": f"IDAT/file ratio {compression_ratio:.2f} — unusually compressible (smooth AI-generated regions)",
                    "impact": "medium",
                    "score_add": 0.12,
                })

    if fmt == "jpeg" and len(data) > 500:
        # JPEG: Quantization table analysis. AI-generated JPEGs re-saved from PNG
        # or directly exported often use uniform/low quantization values (quality 95+).
        # Double-compressed JPEGs (edited) show specific patterns.
        dqt_tables = []
        i = 2
        n = len(data)
        while i < n - 1:
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if marker == 0xDB and i + 4 < n:  # DQT marker
                seg_len = int.from_bytes(data[i + 2:i + 4], "big")
                table_data = data[i + 4:i + 2 + seg_len]
                if len(table_data) >= 64:
                    # Extract first 64 quantization values
                    precision = (table_data[0] >> 4) & 0x0F
                    values = list(table_data[1:65])
                    dqt_tables.append(values)
                i += 2 + seg_len
            elif marker in (0xD8, 0xD9) or 0xD0 <= marker <= 0xD7:
                i += 2
            elif i + 4 <= n:
                seg_len = int.from_bytes(data[i + 2:i + 4], "big")
                i += 2 + seg_len
            else:
                break

        if dqt_tables:
            # Check if quantization is extremely uniform (all values near 1 = quality ~100)
            first_table = dqt_tables[0]
            avg_quant = sum(first_table) / len(first_table)
            variance = sum((v - avg_quant) ** 2 for v in first_table) / len(first_table)

            if avg_quant < 3:
                signals.append({
                    "name": "Near-lossless JPEG quantization",
                    "detail": f"Average QT value {avg_quant:.1f} (quality ~99%) — typical of AI-generated exports",
                    "impact": "low",
                    "score_add": 0.08,
                })
            elif variance < 5 and avg_quant < 10:
                signals.append({
                    "name": "Uniform JPEG quantization tables",
                    "detail": f"QT variance {variance:.1f} — camera photos have varied quantization patterns",
                    "impact": "low",
                    "score_add": 0.06,
                })

    # Generic: byte-pattern uniformity in pixel data region (last 80% of file)
    if len(data) > 2000 and fmt in ("png", "jpeg", "webp"):
        pixel_region = data[len(data) // 5:]  # Skip headers
        if len(pixel_region) > 1000:
            # Check for repeating byte patterns (AI-generated images sometimes
            # have unusual periodicity in their compressed pixel stream)
            sample = pixel_region[:8192]
            byte_pairs = {}
            for j in range(0, len(sample) - 1, 2):
                pair = (sample[j], sample[j + 1])
                byte_pairs[pair] = byte_pairs.get(pair, 0) + 1
            if byte_pairs:
                max_repeat = max(byte_pairs.values())
                pair_ratio = max_repeat / (len(sample) // 2)
                if pair_ratio > 0.05:  # >5% dominated by one byte pair = suspicious
                    signals.append({
                        "name": "Pixel stream periodicity",
                        "detail": f"Dominant byte-pair ratio {pair_ratio:.3f} — suggests synthetic uniformity",
                        "impact": "low",
                        "score_add": 0.06,
                    })

    return signals


def _analyze_media(filename: str, file_bytes: bytes) -> dict:
    """Real, deterministic, explainable manipulation analysis of the raw bytes.

    Signals are split into two tiers so ordinary phone/WhatsApp photos never
    falsely hit a high score:

    - STRONG evidence (named AI tool, editor signature, provenance manifest):
      these are near-certain proof of manipulation/generation on their own,
      so they drive the score directly.
    - WEAK/circumstantial evidence (missing EXIF, "round" dimensions, low
      entropy, byte periodicity): these are common in ANY re-compressed or
      messaging-app-processed photo (WhatsApp/Instagram/Telegram strip EXIF
      from every photo they forward). They are capped at a low ceiling and
      can only ever nudge a "medium" verdict — they can never alone produce
      "high"/"critical", and never reach 100%.
    """
    ext = os.path.splitext(filename)[1].lower()
    is_video = ext in VIDEO_EXTENSIONS
    fmt, width, height = _detect_format_and_dimensions(file_bytes)
    text = _printable_text(file_bytes)
    entropy = _shannon_entropy(file_bytes)

    ai_hits = sorted({sig for sig in AI_SIGNATURES if sig in text})
    editor_hits = sorted({sig for sig in EDITOR_SIGNATURES if sig in text})
    has_exif = (b"Exif\x00\x00" in file_bytes[:200_000]) or any(h in text for h in CAMERA_HINTS)
    c2pa_present = any(tag in text for tag in ("c2pa", "content credentials", "contentauthenticity", "jumbf"))

    strong_score = 0.0   # hard evidence: named tool/editor/provenance signature
    weak_score = 0.0     # circumstantial signals only
    factors = []

    if ai_hits:
        strong_score += 0.70
        factors.append({
            "signal": "AI-generation metadata",
            "detail": ", ".join(ai_hits[:4]),
            "impact": "high",
        })
    if editor_hits:
        strong_score += 0.55
        factors.append({
            "signal": "Image-editor signature",
            "detail": ", ".join(editor_hits[:4]),
            "impact": "high",
        })
    if c2pa_present and not ai_hits:
        strong_score += 0.35
        factors.append({
            "signal": "Content-provenance (C2PA) manifest",
            "detail": "AI/edit provenance markers embedded",
            "impact": "medium",
        })

    # --- Weak/circumstantial signals (heavily capped — see docstring) ---
    if not has_exif and fmt in ("png", "webp"):
        weak_score += 0.10
        factors.append({
            "signal": "No camera EXIF metadata",
            "detail": f"{fmt.upper()} without capture metadata — common for screenshots, "
                      f"messaging-app re-saves, and generated/edited media alike; weak signal on its own",
            "impact": "low",
        })
    if width and height:
        if width == height and width in GENERATIVE_CANVAS:
            weak_score += 0.10
            factors.append({
                "signal": "Generative canvas size",
                "detail": f"{width}x{height} square — seen in diffusion/GAN outputs, but also thumbnails/avatars",
                "impact": "low",
            })
        elif width in GENERATIVE_CANVAS and height in GENERATIVE_CANVAS:
            weak_score += 0.06
            factors.append({
                "signal": "Model-preset dimensions",
                "detail": f"{width}x{height} matches common generation presets (also common resize targets)",
                "impact": "low",
            })
    if fmt in ("png", "jpeg", "webp") and 0 < entropy < 6.0:
        weak_score += 0.06
        factors.append({
            "signal": "Low byte entropy",
            "detail": f"entropy {entropy}/8 is smoother than a typical noisy photo",
            "impact": "low",
        })

    # Pixel-level statistical analysis — also weak/circumstantial.
    pixel_signals = _pixel_level_analysis(file_bytes, fmt)
    for signal in pixel_signals:
        weak_score += signal["score_add"] * 0.5  # halve: these are the least reliable signals
        factors.append({
            "signal": signal["name"],
            "detail": signal["detail"],
            "impact": "low",
        })

    # Cap the ENTIRE weak-evidence contribution: circumstantial signals alone
    # can never push a genuine photo past "medium" risk. Real evidence (strong
    # signals) is required to reach "high"/"critical".
    weak_score = min(weak_score, 0.45)

    score = strong_score + weak_score

    # Positive authenticity signal: genuine camera metadata is real evidence
    # of an authentic capture pipeline and meaningfully reduces suspicion.
    if has_exif and not ai_hits and not editor_hits:
        score = max(0.0, score - 0.25)
        factors.append({
            "signal": "Genuine camera EXIF present",
            "detail": "capture metadata (make/model/exposure) consistent with an authentic photo",
            "impact": "reassuring",
        })

    if not factors:
        factors.append({
            "signal": "No manipulation markers",
            "detail": "no AI/editor/provenance signatures found in file bytes",
            "impact": "reassuring",
        })

    score = max(0.0, min(1.0, score))
    # Require at least some strong evidence to call it a deepfake outright —
    # weak signals alone (common to any re-compressed photo) never suffice.
    is_deepfake = strong_score >= 0.35 and score >= 0.6

    # Risk tier also requires strong evidence to reach high/critical — a photo
    # with only circumstantial signals (no EXIF, round dimensions, etc.) caps
    # at "medium" at most, no matter how many weak signals stack up.
    if strong_score >= 0.35 and score >= 0.85:
        risk_level = "critical"
    elif strong_score >= 0.35 and score >= 0.6:
        risk_level = "high"
    elif score >= 0.25:
        risk_level = "medium"
    else:
        risk_level = "low"

    analysis_details = {
        "detected_format": fmt.upper() if fmt != "unknown" else (ext.upper().lstrip(".") or "UNKNOWN"),
        "dimensions": f"{width}x{height}" if (width and height) else ("video/stream" if is_video else "unknown"),
        "byte_entropy": entropy,
        "camera_metadata": "present" if has_exif else "absent",
        "ai_generator_signatures": ", ".join(ai_hits) if ai_hits else "none",
        "editor_signatures": ", ".join(editor_hits) if editor_hits else "none",
        "c2pa_provenance": "detected" if c2pa_present else "none",
        "signals_evaluated": len(factors),
        "hard_evidence_score": round(strong_score, 3),
        "circumstantial_score": round(weak_score, 3),
        "analysis_method": "Byte-level metadata & structural forensics (advisory heuristic)",
    }

    if is_deepfake:
        recommendations = [
            "HIGH RISK: Byte-level forensics found strong manipulation/AI-generation markers.",
            "Route to the cyber cell for certified forensic verification before evidentiary use.",
            "Preserve the original file and document its chain of custody.",
            "Cross-reference the source and any metadata timestamps.",
        ]
    elif risk_level == "medium":
        recommendations = [
            "INCONCLUSIVE: Some manipulation signals present but not decisive.",
            "Request the original (unedited) file or a higher-resolution version.",
            "Manual forensic review recommended before relying on this media.",
        ]
    else:
        recommendations = [
            "LOW RISK: No significant manipulation or AI-generation markers in the file bytes.",
            "Media appears authentic on metadata/structural analysis.",
            "This is advisory only; certified lab verification is still required for court.",
        ]

    return {
        "is_deepfake": is_deepfake,
        "confidence": round(score, 4),
        "risk_level": risk_level,
        "analysis_details": analysis_details,
        "recommendations": recommendations,
        "factors": factors,
    }


@router.post("/detect", response_model=DeepfakeResult)
async def detect_deepfake(
    file: UploadFile = File(..., description="Image or video file to analyze"),
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Upload an image/video for byte-level media-forensic analysis.

    Inspects the real file content for AI-generation metadata, editor
    signatures, provenance manifests, camera EXIF, generative canvas sizes and
    byte entropy, and returns an explainable, deterministic verdict.
    """
    if not file.filename:
        raise HTTPException(status_code=400, detail="No filename provided")

    ext = os.path.splitext(file.filename)[1].lower()
    if ext not in ALLOWED_EXTENSIONS:
        raise HTTPException(
            status_code=400,
            detail=f"Unsupported file type '{ext}'. Allowed: {', '.join(sorted(ALLOWED_EXTENSIONS))}",
        )

    file_bytes = await file.read()
    file_size = len(file_bytes)

    if file_size > MAX_FILE_SIZE:
        raise HTTPException(
            status_code=400,
            detail=f"File too large ({file_size / 1024 / 1024:.1f}MB). Maximum: 50MB",
        )
    if file_size == 0:
        raise HTTPException(status_code=400, detail="Empty file uploaded")

    result = _analyze_media(file.filename, file_bytes)
    await record_audit_event(
        db,
        current_user,
        "DEEPFAKE_ANALYSIS",
        details=f"Analyzed {file.filename} ({file_size} bytes); risk={result['risk_level']}",
        risk_level=result["risk_level"],
    )

    return DeepfakeResult(
        filename=file.filename,
        file_size=file_size,
        is_deepfake=result["is_deepfake"],
        confidence=result["confidence"],
        risk_level=result["risk_level"],
        analysis_details=result["analysis_details"],
        recommendations=result["recommendations"],
    )
